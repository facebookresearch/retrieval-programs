"""Build the verify (re-answer) and control (resample control) eval sets from harvest repairs.

Place in the pipeline: RL -> harvest -> **verify + control** -> SFT -> resume RL. What this script produces.
Two parquets that differ in exactly one respect:
* treatment (`--out`): the rollout's own turns with the last retrieval program replaced by harvest's repair,
  and the observation replaced by what that repair actually retrieves.
* control (`--control_out`): the same turns with the original program re-executed unchanged.

Usage (normally via `scripts/run_mutation_round.sh`; needs a retriever and a reranker serving):
    python scripts/program_mutation/mutation_verify.py --dump <round>/rollouts/window.jsonl \
        --repairs repairs.jsonl --parquet <datadir>/train.parquet \
        --url http://127.0.0.1:8000/retrieve --rerank_url http://127.0.0.1:6980/rerank \
        --out verify.parquet --control_out control.parquet
"""

from __future__ import annotations

import argparse
import contextlib
import inspect
import io
import json
import pathlib
import re
import sys
import traceback

from mutation_grammar import Program, split_tail
from mutation_harvest import execute, last_turn, parse_program
from mutation_screen import CODE, norm_question, qkey

# Python puts this script's own directory on sys.path, not the repo root. Add the root so documents are split by
# the sandbox SDK's own `_normalize` rather than a copy that could drift from it.
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))

from rpl.search.search_sdk import _normalize  # noqa: E402

# The rollout's own text format, copied from a real dump rather than assumed: a code block is wrapped in
# `\n<code>\n...\n</code>\n\n` and its observation follows immediately as `<output>` + doc lines + `</output>`.
# Reproducing it exactly matters -- the continuation is generated by a policy trained on this surface form, so
# a stray newline is off-policy exposure that the measurement would silently attribute to the repair.
CODE_FMT = "<code>\n{code}\n</code>\n\n"
OBS_FMT = "<output>{body}</output>\n\n"
DOC_FMT = "Doc {n}(Title: {title}) {text}"


def last_turn_span(output: str) -> tuple[int, int] | None:
    """Char span of the final retrieving `<code>...</code>` block, tags included, or None.

    Selection must agree with `mutation_harvest.last_turn` or verify would repair a different turn than harvest
    scored, so the block text it returns is used as the key rather than re-deriving the choice here.
    """
    block = last_turn(output)
    if not block:
        return None
    for m in reversed(list(CODE.finditer(output or ""))):
        if m.group(1) == block:
            return m.start(), m.end()
    return None


def split_contents(contents: str) -> tuple[str, str]:
    """Split a retriever row's `contents` into (title, text), as the sandbox does before the model's `print`."""
    doc = _normalize({"contents": contents}, None)
    return doc["title"], doc["text"]


def exec_tail(docs, tail: str, result_var: str) -> str:
    """What the policy's own post-retrieval lines print, given the repaired retrieval."""
    rows = [{"id": k, "title": t, "text": x}
            for k, (t, x) in ((k, split_contents(v)) for k, v in docs.items())]
    ns: dict = {"__name__": "__main__", result_var: rows, "candidates": rows}
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(tail, "<model_code>", "exec"), ns)
    except BaseException:
        tb = traceback.format_exc().rstrip().splitlines()
        return tb[-1].strip() if tb else "error"
    return buf.getvalue()


def executor_observation_is_error_or_stdout() -> bool:
    """Does `CodeExecutor.observation()` still return the error when set, else stdout?

    `exec_tail` reproduces that choice. If the executor starts combining the two, every verify observation
    for a failing tail would be formatted differently than the policy ever saw one.
    """
    p = pathlib.Path(__file__).resolve().parents[2] / "rpl" / "llm_agent" / "code_executor.py"
    try:
        src = p.read_text()
    except OSError:
        return False
    return "if self.error:\n            return self.error\n        return self.stdout" in src


def render_observation(docs, tail: str = "", result_var: str = "") -> str:
    """The `<output>` block a printing program produces for `docs`.

    `docs` is `run_program`'s `{doc_id: contents}` mapping, in insertion (rank) order. Mirrors the print
    statement `mutation_grammar.Program.render` emits, which is the idiom the RPL prompts elicit;
    `grammar_print_format` pins the two together.
    """
    if tail and result_var:
        return OBS_FMT.format(body=exec_tail(docs, tail, result_var).strip())
    contents_list = list(docs.values()) if isinstance(docs, dict) else list(docs)
    body = "\n".join(DOC_FMT.format(n=i + 1, title=t, text=x)
                     for i, (t, x) in enumerate(split_contents(c) for c in contents_list))
    return OBS_FMT.format(body=body)


def grammar_print_format() -> str | None:
    """`Program.render`'s print format, normalised onto `DOC_FMT`'s placeholder names.

    The observation this script fabricates must be byte-identical to the one the sandbox would print, and the
    two formats live in different files. Reading the grammar's source is what keeps them coupled: a later edit
    to `render()` then fails loudly here instead of shifting every verify observation by a character.
    """
    src = inspect.getsource(Program.render)
    # The print line sits inside a string literal in `render`, so its quotes are backslash-escaped in source.
    m = re.search(r'print\(f\\?"(.*?)\\?"\)', src)
    if not m:
        return None
    return (m.group(1).replace("{i+1}", "{n}")
            .replace("{doc['title']}", "{title}").replace("{doc['text']}", "{text}"))


def build_prefix(output: str, code: str, docs, tail: str = "", result_var: str = "") -> str | None:
    """Everything up to and including the (possibly replaced) last retrieval turn and its observation.

    Anything the model generated after that observation is dropped: it is the continuation being re-measured.
    """
    span = last_turn_span(output)
    if span is None:
        return None
    return output[:span[0]] + CODE_FMT.format(code=code.strip()) + render_observation(docs, tail, result_var)


def row_qkey(row) -> str:
    """Join key for one parquet row: the `question` column when it has one, the prompt tail otherwise."""
    q = str(row.get("question", "") or "")
    if q.strip():
        return norm_question(q)[:200]
    prompt = row.get("prompt")
    text = prompt[-1].get("content", "") if prompt is not None and len(prompt) else ""
    return qkey(str(text))[:200]


def load_parquet_rows(path: str):
    """The source parquet as a list of dicts, so verify rows are copies of real rows and inherit prompt + gold."""
    import pandas as pd
    return pd.read_parquet(path)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dump", required=True, help="the train rollout window harvest read (same file, same order)")
    ap.add_argument("--repairs", required=True, help="harvest output jsonl")
    ap.add_argument("--parquet", required=True, help="the train parquet the run used; rows are copied from it")
    ap.add_argument("--url", default="http://127.0.0.1:8000/retrieve")
    ap.add_argument("--rerank_url", default="http://127.0.0.1:6980/rerank")
    ap.add_argument("--out", required=True, help="treatment parquet (repaired program)")
    ap.add_argument("--control_out", default="", help="control parquet (original program re-executed)")
    ap.add_argument("--limit", type=int, default=0, help="0 = all repaired rows")
    a = ap.parse_args()

    if "/val_rollouts/" in a.dump or "/rollouts/" not in a.dump:
        sys.exit(f"ABORT: --dump must be a train dump under rollouts/, got {a.dump}.")
    if grammar_print_format() != DOC_FMT:
        sys.exit(f"ABORT: the grammar now prints {grammar_print_format()!r} but DOC_FMT is {DOC_FMT!r}; every "
                 f"verify observation would be formatted differently than in training.")
    if not executor_observation_is_error_or_stdout():
        sys.exit("ABORT: CodeExecutor.observation() no longer returns error-or-stdout; `exec_tail` would "
                 "format every failing verify observation differently than the policy ever saw one.")

    """
    Step 1: load the repairs and the rollout window, and join each repair to the rollout it repaired.
    """
    # A question has several rollouts in a window (one per group sample and step). Joining by question took the
    # first, often a successful one, and spliced the repair into a trajectory it was not computed on; the join is
    # by the rollout's position in the window, which harvest records as `dump_line`.
    repairs, seen = [], set()
    for line in open(a.repairs):
        if not line.strip():
            continue
        rec = json.loads(line)
        if rec.get("status") == "repaired":
            if "dump_line" not in rec:
                sys.exit(f"ABORT: {a.repairs} has no `dump_line`; re-run mutation_harvest.py so each repair names "
                         f"the rollout it was computed on.")
            key = (rec["dump_line"], rec["repair_code"])
            if key in seen:
                continue
            seen.add(key)
            repairs.append(rec)
    dump = [json.loads(line) for line in open(a.dump) if line.strip()]
    n_q = len({r["question"] for r in repairs})
    print(f"{len(repairs)} repaired rows over {n_q} distinct questions; {len(dump)} rollouts in the dump")

    df = load_parquet_rows(a.parquet)
    by_q = {}
    for i in range(len(df)):
        by_q.setdefault(row_qkey(df.iloc[i]), i)
    by_q.pop("", None)
    # A join key that collapses is indistinguishable downstream from a genuinely unjoinable set, and costs a
    # build plus both evals before anything says so.
    if len(by_q) < max(2, len(df) // 10):
        sys.exit(f"ABORT: the parquet yielded {len(by_q)} distinct join keys for {len(df)} rows; its columns "
                 f"are {list(df.columns)}. Every row keying the same way means the question could not be "
                 f"recovered from either a `question` column or the prompt tail.")

    """
    Step 2: for each repaired row, execute both programs and splice both prefixes.
    """
    cache: dict = {}
    idx, treat_prefix, ctrl_prefix = [], [], []
    skipped: dict[str, int] = {}
    for rec in repairs:
        if a.limit and len(idx) >= a.limit:
            break
        q = rec["question"]
        row = dump[rec["dump_line"]] if rec["dump_line"] < len(dump) else None
        if (row is None or qkey(row.get("input"))[:200] != q
                or last_turn(row.get("output")).strip() != rec["original_code"]):
            sys.exit(f"ABORT: line {rec['dump_line']} of {a.dump} is not the rollout harvest repaired; --dump must be "
                     f"the exact window file harvest read.")
        pidx = by_q.get(q)
        if pidx is None:
            skipped["unjoined"] = skipped.get("unjoined", 0) + 1
            continue
        repaired = parse_program(rec["repair_code"])
        original = parse_program(last_turn(row.get("output")))
        if repaired is None or original is None:
            skipped["unparseable"] = skipped.get("unparseable", 0) + 1
            continue
        # The repair is re-parsed from its rendered text, so a render/parse round-trip bug would silently
        # execute a different program than harvest scored. Its recorded cost is the checksum.
        if list(repaired.cost) != list(rec["repair_cost"]):
            sys.exit(f"ABORT: repair re-parsed to cost {list(repaired.cost)} but harvest recorded "
                     f"{rec['repair_cost']} for {rec['repair_code']!r}; the round-trip is lossy.")
        # The tail belongs to the policy, so treatment and control share it; only retrieval differs.
        rvar, rtail = split_tail(rec["original_code"])
        t = build_prefix(row["output"], rec["repair_code"],
                         execute(repaired, a.url, a.rerank_url, cache), rtail, rvar)
        c = build_prefix(row["output"], rec["original_code"],
                         execute(original, a.url, a.rerank_url, cache), rtail, rvar)
        if t is None or c is None:
            skipped["no_span"] = skipped.get("no_span", 0) + 1
            continue
        idx.append(pidx)
        treat_prefix.append(t)
        ctrl_prefix.append(c)

    # Before the abort, not after: the breakdown is the whole diagnosis, and exiting first threw it away.
    for k, v in sorted(skipped.items()):
        print(f"  skipped {k}: {v}")
    if not idx:
        sys.exit("ABORT: no rows built. A repaired-but-unjoinable set means the dump, repairs and parquet do "
                 "not come from the same run.")

    """
    Step 3: write both parquets as copies of real rows plus the prefix.
    """
    _write(df, idx, treat_prefix, a.out)
    print(f"wrote {len(idx)} treatment rows -> {a.out}")
    if a.control_out:
        _write(df, idx, ctrl_prefix, a.control_out)
        print(f"wrote {len(idx)} control rows -> {a.control_out}")
        print("\nRun BOTH through the eval path with MAX_TURNS=1 SINGLE_PASS=1 (greedy, as reported).\n"
              "verify gain = acc(treatment) - acc(original rollouts, all 0 by selection)\n"
              "attributable to the repair = acc(treatment) - acc(control)")


def _write(df, idx: list[int], prefixes: list[str], path: str) -> None:
    out = df.iloc[idx].copy().reset_index(drop=True)
    # `extra_info` is a per-row dict; copy before mutating so the source frame is untouched between writes.
    extra = []
    for i, p in enumerate(prefixes):
        e = out.at[i, "extra_info"] if "extra_info" in out.columns else None
        e = dict(e) if isinstance(e, dict) else {}
        e["response_prefix"] = p
        # A question may have several valid fixes, so the question is not a key. This id is what lets the
        # eval dump be joined back per repair; without it the downstream SFT silently keeps one per
        # question and a "several fixes" arm is really a one-fix arm. verify and control share the row order,
        # so treatment and control get the same ids.
        e["repair_id"] = float(i)
        extra.append(e)
    out["extra_info"] = extra
    out.to_parquet(path, index=False)


if __name__ == "__main__":
    main()
